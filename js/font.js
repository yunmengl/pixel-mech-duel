  P.glyphAdvance = (ch, scale) => (ch === ' ' ? 4 : 5) * scale + scale;

  P.textWidth = (text, scale = 1) => {
    if (!text) return 0;
    let w = 0;
    for (const raw of String(text)) w += P.glyphAdvance(raw, scale);
    return Math.max(0, w - scale);
  };

  P.drawText = (
    g,
    text,
    x,
    y,
    scale = 1,
    color = '#ffffff',
    align = 'left',
    shadowColor = '#02040a'
  ) => {
    text = String(text).toUpperCase();
    const width = P.textWidth(text, scale);
    let startX = x;
    if (align === 'center') startX = x - width / 2;
    else if (align === 'right') startX = x - width;

    const paint = (offsetX, offsetY, paintColor) => {
      let cursor = startX + offsetX;
      for (const ch of text) {
        const glyph = FONT[ch];
        if (glyph) {
          g.fillStyle = paintColor;
          for (let row = 0; row < glyph.length; row++) {
            const line = glyph[row];
            for (let col = 0; col < line.length; col++) {
              if (line[col] === '1') {
                g.fillRect(
                  Math.round(cursor + col * scale),
                  Math.round(y + offsetY + row * scale),
                  scale,
                  scale
                );
              }
            }
          }
        }
        cursor += P.glyphAdvance(ch, scale);
      }
    };

    if (shadowColor) {
      const s = Math.max(1, Math.round(scale * 0.75));
      paint(s, s, shadowColor);
    }
    paint(0, 0, color);
  };

  P.drawTextSoft = (g, text, x, y, scale, color, align, glowColor) => {
    P.drawText(g, text, x - 1, y, scale, glowColor, align, null);
    P.drawText(g, text, x + 1, y, scale, glowColor, align, null);
    P.drawText(g, text, x, y - 1, scale, glowColor, align, null);
    P.drawText(g, text, x, y + 1, scale, glowColor, align, null);
    P.drawText(g, text, x, y, scale, color, align);
  };
